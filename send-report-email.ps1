# ============================================================
# SEND REPORT EMAIL
# Finds the latest HTML report and emails it via Gmail SMTP
# ============================================================

param(
    [string]$ReportPath = ""
)

# Load credentials
$configPath = "C:\Users\NN Leptop 33\Claude Agents\email-config.ps1"
if (!(Test-Path $configPath)) {
    Write-Error "email-config.ps1 not found. Please fill in your credentials first."
    exit 1
}
. $configPath

# Find the report to send
if ($ReportPath -eq "") {
    # Auto-find the most recently created HTML report
    $report = Get-ChildItem -Path "C:\Users\NN Leptop 33\Claude Agents\" `
        -Filter "india-school-services-report-*.html" |
        Sort-Object LastWriteTime -Descending |
        Select-Object -First 1

    if ($null -eq $report) {
        Write-Error "No HTML report found. Research may not have completed yet."
        exit 1
    }
    $ReportPath = $report.FullName
}

if (!(Test-Path $ReportPath)) {
    Write-Error "Report file not found: $ReportPath"
    exit 1
}

$reportName = Split-Path $ReportPath -Leaf
$dateStamp  = Get-Date -Format "dd MMM yyyy"
$subject    = "$EMAIL_SUBJECT_PREFIX | $dateStamp"

Write-Host "Sending report: $reportName"
Write-Host "To: $EMAIL_TO"

# Read HTML content for inline body
$htmlBody = Get-Content $ReportPath -Raw -Encoding UTF8

# Build a wrapper email body
$emailBody = @"
<html>
<body style="font-family: Arial, sans-serif; color: #333; max-width: 600px; margin: 0 auto; padding: 20px;">
  <div style="background: #1a2744; color: white; padding: 16px 20px; border-radius: 8px 8px 0 0;">
    <h2 style="margin:0; font-size:18px;">India School Services — Weekly Competitive Report</h2>
    <p style="margin:4px 0 0 0; font-size:13px; opacity:0.8;">$dateStamp</p>
  </div>
  <div style="background: #f8f9fa; padding: 16px 20px; border: 1px solid #ddd; border-top: none; border-radius: 0 0 8px 8px;">
    <p style="margin:0 0 12px 0;">Your weekly competitive intelligence report is ready.</p>
    <p style="margin:0 0 12px 0;">The full interactive report is attached as an HTML file.
    Open it in your browser for the best experience — tables, cards, and colour coding all render correctly.</p>
    <p style="margin:0; font-size:12px; color:#888;">
      Generated by Claude Code agent team | Data reflects research as of $dateStamp
    </p>
  </div>
</body>
</html>
"@

# Send via Gmail SMTP using .NET SmtpClient (supports TLS 1.2)
try {
    Add-Type -AssemblyName System.Net.Mail

    # Force TLS 1.2
    [System.Net.ServicePointManager]::SecurityProtocol = [System.Net.SecurityProtocolType]::Tls12

    $smtp   = New-Object System.Net.Mail.SmtpClient("smtp.gmail.com", 587)
    $smtp.EnableSsl   = $true
    $smtp.Credentials = New-Object System.Net.NetworkCredential($EMAIL_FROM, $EMAIL_APP_PASSWORD)

    $mail             = New-Object System.Net.Mail.MailMessage
    $mail.From        = $EMAIL_FROM
    $mail.To.Add($EMAIL_TO)
    $mail.Subject     = $subject
    $mail.Body        = $emailBody
    $mail.IsBodyHtml  = $true

    # Attach the HTML report
    $attachment = New-Object System.Net.Mail.Attachment($ReportPath)
    $mail.Attachments.Add($attachment)

    $smtp.Send($mail)
    $attachment.Dispose()
    $mail.Dispose()
    $smtp.Dispose()

    Write-Host "Email sent successfully." -ForegroundColor Green

} catch {
    Write-Error "Failed to send email: $_"
    exit 1
}
